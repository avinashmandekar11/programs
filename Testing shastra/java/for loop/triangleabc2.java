public class triangleabc2 {
    public static void main(String[] args) {
     
        char ab ='a';
        int n=5;
        for(int i=1;i<=n;i++){
            //char ab ='A';
            for(int j=1;j<=i;j++){
               
                System.out.print(ab);
              ab++;
            }

            System.out.println();
        }


    }
}
